/// The measurements of a pocket of a table.
struct PocketShape {
    /// Between the jaws along the cushion lines.
    var mouth: Double
    /// Of a jaw's facing from the line of its cushion, toward the outside.
    var deviation: Double
    /// The rounding of the jaw.
    var tipRadius: Double
    /// The length of the facing.
    var facing: Double
    /// From the mouth to the edge of the hole.
    var shelf: Double
    var hole: Double
    var cup: Double
    var depth: Double
}
